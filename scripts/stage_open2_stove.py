#!/usr/bin/env python3
"""Stage the released Open2 compiler plus an explicitly reused OpenGPU SDK.

Local files only. Never install over an existing stove or copy old libc,
libpthread, libstdc++ or compiler binaries from the SDK donor.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import tarfile
import tempfile
from pathlib import Path

RELEASE = '16.2.0-open2'
ARCHIVE_SHA256 = '5ece099a6fb8923a35eacf420bfa5fced06546ac1822714c76a2ae52466c978c'
TOP = 'openamigagcc-16.2.0-open2-x86_64-linux'
SDK_LIBRARIES = ('libSDL2*.a', 'libGL.a', 'libmgl.a', 'libminigl.a', 'libtinygl.a')


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def stage(archive: Path, ndk_prefix: Path, sdk_prefix: Path, destination: Path) -> dict:
    if not hasattr(tarfile, 'data_filter'):
        raise ValueError('Python with tarfile.data_filter is required (Python 3.12+ recommended)')
    destination = destination.absolute()
    if destination.exists():
        raise ValueError('Refusing to overwrite an existing stove: ' + str(destination))
    if sha256(archive) != ARCHIVE_SHA256:
        raise ValueError('Open2 compiler archive SHA-256 does not match the published release')
    if not (ndk_prefix / 'm68k-amigaos/ndk-include/proto/exec.h').is_file():
        raise ValueError('Supply an NDK prefix generated by the Open2 install procedure')
    sdk_config = sdk_prefix / 'bin/sdl2-config'
    if not sdk_config.is_file() or not os.access(sdk_config, os.X_OK):
        raise ValueError('Supply an existing OpenGPU SDK stove prefix with executable sdl2-config')
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.open2-stage-', dir=destination.parent) as tmp:
        staging = Path(tmp)
        with tarfile.open(archive, 'r:xz') as tf:
            # Python's data filter rejects traversal, unsafe links and special files.
            tf.extractall(staging, filter='data')
        prefix = staging / TOP
        if not (prefix / 'bin/m68k-amigaos-g++').is_file():
            raise ValueError('Unexpected compiler archive layout')
        prefix.rename(staging / 'prefix')
        prefix = staging / 'prefix'
        # Protect every release file, including any NDK or standard headers.
        compiler_files = [p for p in prefix.rglob('*') if p.is_file()]
        before = {str(p.relative_to(prefix)): sha256(p) for p in compiler_files}
        supplemental = []

        def copy(src: Path, dst: Path) -> None:
            if dst.exists():
                if sha256(src) != sha256(dst):
                    raise ValueError('Supplement would overwrite a release file: ' + str(dst.relative_to(prefix)))
                return
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            supplemental.append({'destination': str(dst.relative_to(prefix)),
                                 'source': str(src), 'sha256': sha256(dst)})

        for name in ('ndk-include', 'ndk13-include', 'ndk'):
            src = ndk_prefix / 'm68k-amigaos' / name
            if src.exists():
                for header in sorted(src.rglob('*')):
                    if header.is_file():
                        if not header.resolve().is_relative_to(ndk_prefix.resolve()):
                            raise ValueError('NDK symlink points outside the supplied prefix: ' + str(header))
                        copy(header, prefix / 'm68k-amigaos' / name / header.relative_to(src))
        # Keep release-provided headers. Additional SDK/NDK device headers are
        # admitted only when absent, and every copied file is fingerprinted.
        includes = sdk_prefix / 'm68k-amigaos/include'
        for src in sorted(includes.rglob('*')):
            if src.is_file():
                dst = prefix / 'm68k-amigaos/include' / src.relative_to(includes)
                if not dst.exists():
                    copy(src, dst)
        for pattern in SDK_LIBRARIES:
            for src in sorted((sdk_prefix / 'm68k-amigaos/lib').glob(pattern)):
                copy(src, prefix / 'm68k-amigaos/lib' / src.name)
        for name in ('cmake', 'pkgconfig'):
            base = sdk_prefix / 'm68k-amigaos/lib' / name
            for src in sorted(base.rglob('*')):
                if src.is_file():
                    copy(src, prefix / 'm68k-amigaos/lib' / name / src.relative_to(base))
        copy(sdk_prefix / 'bin/sdl2-config', prefix / 'bin/sdl2-config')
        for relative, expected in before.items():
            if sha256(prefix / relative) != expected:
                raise ValueError('SDK overlay changed an Open2 compiler/runtime file: ' + relative)
        if not (prefix / 'm68k-amigaos/lib/libSDL2.a').is_file():
            raise ValueError('SDK donor did not supply the OpenGPU SDL2 client archive')
        receipt = {
            'schema': 1, 'release': RELEASE, 'compiler_archive': str(archive),
            'archive_sha256': ARCHIVE_SHA256, 'ndk_source': str(ndk_prefix),
            'sdk_source': str(sdk_prefix), 'compiler_runtime_sha256': before,
            'sdk_status': 'reused, not rebuilt or runtime-qualified by this tool',
            'supplemental_files': supplemental, 'runtime_state': 'not_tested',
        }
        receipt['cxx_version'] = subprocess.check_output(
            [str(prefix / 'bin/m68k-amigaos-g++'), '--version'], text=True).splitlines()[0]
        (staging / 'provenance.json').write_text(json.dumps(receipt, indent=2) + '\n')
        # Move complete verified tree together; never leave a half-populated stove.
        staging.rename(destination)
    return receipt


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--archive', type=Path, required=True)
    p.add_argument('--ndk-prefix', type=Path, required=True)
    p.add_argument('--sdk-prefix', type=Path, required=True)
    p.add_argument('--destination', type=Path, required=True)
    args = p.parse_args()
    try:
        receipt = stage(args.archive, args.ndk_prefix, args.sdk_prefix, args.destination)
    except (OSError, ValueError, tarfile.TarError, subprocess.CalledProcessError) as exc:
        p.exit(2, f'Open2 staging refused: {exc}\n')
    print(f'STAGED {receipt["release"]}: {args.destination.absolute()}')
    print('Existing OpenGPU SDK imported with hashes; its archives still require qualification.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
